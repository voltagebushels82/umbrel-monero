import * as constants from '../utils/const.js';
import * as diskService from '../services/disk.js';
import { ValidationError } from '../models/errors.js';
import { isValidAddress } from '../build/services/monerod.js';

const DEFAULT_ADVANCED_SETTINGS = {
  tor: process.env.MONERO_TOR !== 'false',
  // Retain the saved key for compatibility: proxy clearnet peers through Tor.
  torOnly: false,
  i2p: process.env.MONERO_I2P === 'true',
  incomingConnections: false,
  dbSyncMode: constants.MONERO_SYNC_MODE,
  dbSyncType: constants.MONERO_SYNC_TYPE,
  dbBlocksPerSync: constants.MONERO_BLOCKS_PER_SYNC,
  upnp: true,
  checkpoint: true,
  publicNode: true,
  moneroAddress: '',
  zmq: false,
  hidePort: true,
  blockNotify: false,
  prune: false,
  mining: false,
  minercpuTarget: 40,
  dbSalvage: false,
  network: constants.MONERO_DEFAULT_NETWORK,
};


export function normalizeSettings(input = {}) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) throw new ValidationError('Settings must be an object');
  const settings = {...DEFAULT_ADVANCED_SETTINGS};
  for (const key of Object.keys(settings)) {
    if (!Object.hasOwn(input, key)) continue;
    if (typeof input[key] !== typeof settings[key]) throw new ValidationError(`Invalid ${key}`);
    settings[key] = input[key];
  }
  if (settings.network === 'test') settings.network = 'testnet';
  if (!['mainnet', 'testnet', 'stagenet'].includes(settings.network)) throw new ValidationError('Invalid network');
  if (!['fast', 'fastest', 'safe'].includes(settings.dbSyncMode)) throw new ValidationError('Invalid database sync mode');
  if (/[\r\n\0]/.test(settings.moneroAddress)) throw new ValidationError('Invalid mining address');
  if (settings.mining && (!Number.isInteger(settings.minercpuTarget) || settings.minercpuTarget < 1 || settings.minercpuTarget > 100)) throw new ValidationError('Mining CPU target must be between 1 and 100');
  return settings;
}

function endpoint(host, port, label) {
  if (!host || !/^[a-zA-Z0-9.:-]+$/.test(host) || !/^\d+$/.test(String(port)) || Number(port) < 1 || Number(port) > 65535) {
    throw new ValidationError(`${label} host/port is not configured`);
  }
  return `${host}:${port}`;
}

export function settingsToMultilineConfString(input) {
  const settings = normalizeSettings(input);
  const lines = ['# Generated by Monero Node', 'rpc-ssl=autodetect'];
  if (settings.network !== 'mainnet') lines.push(`${settings.network}=1`);
  lines.push('out-peers=12', `in-peers=${settings.incomingConnections && !settings.torOnly ? 12 : 0}`,
    'limit-rate-up=1048576', 'limit-rate-down=1048576', `db-sync-mode=${settings.dbSyncMode}`,
    `p2p-bind-ip=${settings.torOnly ? '127.0.0.1' : '0.0.0.0'}`, `p2p-bind-port=${constants.MONERO_P2P_PORT}`,
    `igd=${settings.upnp && settings.incomingConnections && !settings.torOnly ? 'enabled' : 'disabled'}`);
  if (settings.checkpoint && !settings.torOnly) lines.push('enforce-dns-checkpointing=1');
  if (settings.prune) lines.push('prune-blockchain=1');
  if (settings.dbSalvage) lines.push('db-salvage=1');
  if (settings.hidePort || !settings.incomingConnections || settings.torOnly) lines.push('hide-my-port=1');
  if (settings.mining) {
    if (!settings.moneroAddress) throw new ValidationError('Mining requires a reward address');
    lines.push('bg-mining-enable=1', `start-mining=${settings.moneroAddress}`, `bg-mining-miner-target=${settings.minercpuTarget}`);
  }
  if (settings.torOnly) {
    const proxy = endpoint(constants.TOR_PROXY_IP, constants.TOR_PROXY_PORT, 'Tor SOCKS proxy');
    lines.push(`proxy=${proxy}`, 'proxy-allow-dns-leaks=0', 'disable-dns-checkpoints=1', 'enable-dns-blocklist=0', 'check-updates=disabled');
  }
  if (settings.tor) {
    const proxy = endpoint(constants.TOR_PROXY_IP, constants.TOR_PROXY_PORT, 'Tor SOCKS proxy');
    lines.push(`tx-proxy=tor,${proxy}`);
    if (settings.incomingConnections) {
      const onion = constants.MONERO_P2P_HIDDEN_SERVICE;
      if (!/^[a-z2-7]{56}\.onion$/.test(onion || '')) throw new ValidationError('A valid Tor v3 P2P hidden service is required');
      lines.push(`anonymous-inbound=${endpoint(onion, constants.MONERO_ONION_P2P_PORT, 'Tor inbound')},0.0.0.0:${constants.MONERO_ONION_P2P_PORT},64`);
    }
  }
  if (settings.i2p) {
    lines.push(`tx-proxy=i2p,${endpoint(constants.I2P_DAEMON_IP, constants.I2P_DAEMON_PORT, 'I2P SOCKS proxy')}`);
    if (settings.incomingConnections) {
      const address = constants.MONERO_I2P_HIDDEN_SERVICE;
      if (!/^[a-z2-7]{52}\.b32\.i2p$/.test(address || '')) throw new ValidationError('A valid I2P hidden service is required');
      lines.push(`anonymous-inbound=${address},0.0.0.0:${constants.MONERO_I2P_P2P_PORT},25`);
    }
  }
  lines.push('rpc-restricted-bind-ip=0.0.0.0', `rpc-restricted-bind-port=${constants.MONERO_RESTRICTED_RPC_PORT}`, 'confirm-external-bind=1');
  if (settings.publicNode && !settings.torOnly) lines.push('public-node=1');
  if (settings.zmq) {
    if ([constants.MONERO_P2P_PORT, constants.MONERO_RPC_PORT, constants.MONERO_ONION_P2P_PORT, constants.MONERO_RESTRICTED_RPC_PORT, constants.MONERO_ZMQ_PORT].includes(constants.MONERO_ZMQ_PUB_PORT)) throw new ValidationError('ZMQ publish port must be distinct from other ports');
    lines.push('confirm-zmq-rpc-external-bind=1', 'restricted-zmq-rpc=1', `zmq-rpc-bind-ip=0.0.0.0`, `zmq-rpc-bind-port=${constants.MONERO_ZMQ_PORT}`, `zmq-pub=tcp://0.0.0.0:${constants.MONERO_ZMQ_PUB_PORT}`);
  } else lines.push('no-zmq=1');
  return lines.join('\n') + '\n';
}

export async function getJsonStore() {
  try {
    const jsonStore = await diskService.readJsonFile(constants.JSON_STORE_FILE);
    return normalizeSettings(jsonStore);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return {...DEFAULT_ADVANCED_SETTINGS};
  }
}

// Serialize the config and settings pair so concurrent requests cannot interleave writes.
let pendingWrite = Promise.resolve();
async function applyMoneroConfig(input, overwrite = true, merge = false) {
  const operation = pendingWrite.then(async () => {
    const settings = normalizeSettings(merge ? {...await getJsonStore(), ...input} : input);
    const config = settingsToMultilineConfString(settings);
    if (settings.mining && !await isValidAddress(settings.moneroAddress, settings.network)) throw new ValidationError('Invalid reward address for the selected network');
    if (overwrite || !await diskService.fileExists(constants.MONERO_CONF_FILEPATH)) {
      await diskService.writePlainTextFile(constants.MONERO_CONF_FILEPATH, config);
    }
    await diskService.writeJsonFile(constants.JSON_STORE_FILE, settings);
  });
  pendingWrite = operation.catch(() => {});
  return operation;
}
export async function applyCustomMoneroConfig(config, overwrite = true) {
  if (!config || typeof config !== "object" || Array.isArray(config)) throw new ValidationError("Settings must be an object");
  return applyMoneroConfig(config, overwrite, true);
}
export async function applyDefaultMoneroConfig() {
  return applyMoneroConfig(DEFAULT_ADVANCED_SETTINGS);
}

// Repair only signatures produced by older versions; leave unrelated hand-written config alone.
export async function repairLegacyConfig() {
  if (!await diskService.fileExists(constants.MONERO_CONF_FILEPATH)) return false;
  const contents = await diskService.readUtf8File(constants.MONERO_CONF_FILEPATH);
  let legacyNetwork = false;
  if (await diskService.fileExists(constants.JSON_STORE_FILE)) {
    legacyNetwork = (await diskService.readJsonFile(constants.JSON_STORE_FILE)).network === 'test';
  }
  if (!legacyNetwork && !/^anonymous-inbound=.*(?:undefined|,monerod:)/m.test(contents)) return false;
  await applyCustomMoneroConfig(await getJsonStore());
  return true;
}
